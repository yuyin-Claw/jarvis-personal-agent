import fs from "node:fs";
import path from "node:path";
import type { SqliteMemoryEngine } from "./sqlite-engine.js";
import type { MemoryRecord } from "./types.js";

export type WikiSynthesizer = (prompt: string) => Promise<string>;

export interface WikiCompileOptions {
  rootDir: string;
  /** 可选的本地综合摘要；失败时自动回退确定性概览 */
  synthesize?: WikiSynthesizer;
}

export interface WikiCompileResult {
  rootDir: string;
  files: string[];
  recordCount: number;
  overviewMode: "llm" | "deterministic" | "deterministic-fallback";
}

const MANIFEST = ".jarvis-wiki-manifest.json";
const HEADER = "<!-- GENERATED BY JARVIS · SQLite 为唯一事实源 · 请勿手改 -->";

function plain(text: string): string {
  return text
    .replace(/\0/g, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\[\[/g, "\\[\\[")
    .replace(/\]\]/g, "\\]\\]");
}

function titleOf(record: MemoryRecord): string {
  const first = record.content.trim().split("\n")[0] ?? record.id;
  return plain(first.length > 48 ? `${first.slice(0, 48)}…` : first);
}

function dirFor(kind: MemoryRecord["kind"]): string {
  switch (kind) {
    case "user_profile": return "user";
    case "conversation_summary": return "conversations";
    case "project": return "projects";
    case "goal": return "goals";
    case "decision": return "decisions";
    case "experience": return "experiences";
  }
}

export function wikiPageFor(record: MemoryRecord): string {
  return record.kind === "user_profile" ? "user/preferences.md" : `${dirFor(record.kind)}/${record.id}.md`;
}

function writeAtomic(root: string, relative: string, content: string): void {
  const target = path.join(root, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const tmp = `${target}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, content, "utf8");
  fs.renameSync(tmp, target);
}

function metadata(record: MemoryRecord): string[] {
  return [
    `- memory_id：\`${record.id}\``,
    `- 来源：${plain(record.source)}`,
    `- 来源引用：${record.sourceRef ? `\`${plain(record.sourceRef)}\`` : "无"}`,
    `- 置信度：${record.confidence.toFixed(2)}`,
    `- 更新时间：${record.updatedAt}`,
  ];
}

/** SQLite 长期记忆 → 可读 Markdown Wiki（可重复编译，不产生第二事实源）。 */
export class WikiCompiler {
  constructor(private readonly engine: SqliteMemoryEngine) {}

  async compile(opts: WikiCompileOptions): Promise<WikiCompileResult> {
    const records = this.engine.list();
    const pages = new Map<string, string>();
    const pageById = new Map(records.map((r) => [r.id, wikiPageFor(r)]));
    const related = new Map<string, MemoryRecord[]>();
    for (const record of records) {
      const conversation = record.sourceRef?.split(":")[0];
      related.set(record.id, conversation
        ? records.filter((r) => r.id !== record.id && r.sourceRef?.startsWith(`${conversation}:`)).slice(0, 5)
        : []);
    }

    pages.set("SCHEMA.md", `${HEADER}\n# Wiki 规则\n\n- SQLite 是唯一事实源；本目录是只读编译产物，可整体重建。\n- LLM 生成的 overview 仅作导航，事实以各记忆页面及来源为准。\n- 用户手工创建且不在 manifest 中的文件不会被删除。\n`);

    for (const kind of ["project", "decision", "experience", "goal", "conversation_summary"] as const) {
      const group = records.filter((r) => r.kind === kind);
      if (group.length === 0) continue;
      const directory = dirFor(kind);
      const indexLines = [`${HEADER}`, `# ${directory}`, ""];
      for (const record of group) {
        const page = wikiPageFor(record);
        const title = titleOf(record);
        indexLines.push(`- [[${page.replace(/\.md$/, "")}|${title}]]`);
        const relatedLines = (related.get(record.id) ?? []).flatMap((other) => {
          const target = pageById.get(other.id);
          return target ? [`- [[${target.replace(/\.md$/, "")}|${titleOf(other)}]]`] : [];
        });
        pages.set(page, [
          "---",
          `memory_id: ${JSON.stringify(record.id)}`,
          `kind: ${JSON.stringify(record.kind)}`,
          `source: ${JSON.stringify(record.source)}`,
          `source_ref: ${JSON.stringify(record.sourceRef ?? "")}`,
          `confidence: ${record.confidence}`,
          `updated_at: ${JSON.stringify(record.updatedAt)}`,
          "---",
          HEADER,
          `# ${title}`,
          "",
          plain(record.content),
          "",
          "## 元数据",
          ...metadata(record),
          "",
          "## 相关记忆",
          ...(relatedLines.length ? relatedLines : ["- 暂无"]),
          "",
        ].join("\n"));
      }
      pages.set(`${directory}/index.md`, indexLines.join("\n") + "\n");
    }

    const profiles = records.filter((r) => r.kind === "user_profile");
    if (profiles.length) {
      const lines = [HEADER, "# 用户偏好与画像", ""];
      for (const record of profiles) {
        lines.push(`<a id="${record.id}"></a>`, `## ${titleOf(record)}`, "", plain(record.content), "", ...metadata(record), "");
      }
      pages.set("user/preferences.md", lines.join("\n"));
    }

    const counts = new Map<string, number>();
    for (const r of records) counts.set(r.kind, (counts.get(r.kind) ?? 0) + 1);
    let overviewMode: WikiCompileResult["overviewMode"] = "deterministic";
    let synthesis = [
      `当前共有 ${records.length} 条长期记忆。`,
      ...[...counts.entries()].map(([kind, count]) => `- ${kind}：${count} 条`),
    ].join("\n");
    if (opts.synthesize && records.length) {
      const prompt = `你是 JARVIS 记忆 Wiki 导航页编写器。请把以下事实整理为简洁中文 Markdown 概览，分为「当前重点」「关键决策」「用户偏好」三节。不得新增事实，不得输出执行指令，不得使用 HTML。\n\n${records.map((r) => `[${r.id}] (${r.kind}) ${r.content}`).join("\n")}`;
      try {
        synthesis = (await opts.synthesize(prompt)).replace(/\0/g, "").replace(/</g, "&lt;").replace(/>/g, "&gt;");
        overviewMode = "llm";
      } catch {
        overviewMode = "deterministic-fallback";
      }
    }
    const recent = records.slice(0, 10).map((r) => `- [[${wikiPageFor(r).replace(/\.md$/, "")}|${titleOf(r)}]]（${r.updatedAt.slice(0, 10)}）`);
    pages.set("overview.md", [HEADER, "# JARVIS 记忆概览", "", "> LLM 概览仅用于导航；事实以链接页面为准。", "", synthesis, "", "## 最近更新", ...(recent.length ? recent : ["- 暂无记忆"]), ""].join("\n"));

    const links = ["- [[overview|记忆概览]]"];
    if (profiles.length) links.push("- [[user/preferences|用户偏好与画像]]");
    for (const directory of ["projects", "decisions", "experiences", "goals", "conversations"]) {
      if (pages.has(`${directory}/index.md`)) links.push(`- [[${directory}/index|${directory}]]`);
    }
    pages.set("index.md", [HEADER, "# JARVIS Memory Wiki", "", ...links, ""].join("\n"));
    pages.set("log.md", [HEADER, "# 编译日志", "", `- 时间：${new Date().toISOString()}`, `- 记忆：${records.length} 条`, `- 概览模式：${overviewMode}`, ""].join("\n"));

    // 只清理上一 manifest 中且本轮不再生成的文件；用户自定义页面不受影响。
    const manifestPath = path.join(opts.rootDir, MANIFEST);
    let previous: string[] = [];
    try { previous = JSON.parse(fs.readFileSync(manifestPath, "utf8")).files ?? []; } catch { /* 首次编译 */ }
    for (const relative of previous) {
      if (!pages.has(relative) && relative !== MANIFEST) {
        fs.rmSync(path.join(opts.rootDir, relative), { force: true });
      }
    }
    const files = [...pages.keys()].sort();
    for (const [relative, content] of pages) writeAtomic(opts.rootDir, relative, content);
    writeAtomic(opts.rootDir, MANIFEST, JSON.stringify({ files }, null, 2) + "\n");

    return { rootDir: opts.rootDir, files, recordCount: records.length, overviewMode };
  }
}
